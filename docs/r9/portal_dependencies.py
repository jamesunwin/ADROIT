"""R9: which unverified records leave each library portal's benchmark point undecided (verification order aid).

Each portal of the library is evaluated at its benchmark point twice: with verified records only (the default),
and with unverified records allowed. A constraint that is undecided in the first and decided in the second waits
for its record's verification. Writes docs/r9/portal_dependencies.md. $0, no network; run from the repository root:

    uv run python docs/r9/portal_dependencies.py
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
OUT = Path(__file__).with_name("portal_dependencies.md")
TITLES = {"IceCube 2016": "icecube-1612.05949-sd/si",            # pending texts that name a record by title
          "Fermi-LAT 2015": "fermi-1503.02641-dsph"}
NAMED = {"Fermi-LAT dwarfs": "fermi-2311.04982-spectral",         # texts naming no record: by their constraint
         "L_μ − L_τ (CCFR)": "ccfr-1406.2332-trident", "colliders (CMS)": "cms-2405.13778-V1/A1/V2/A2"}


def blocked(point) -> dict[str, str]:
    """constraint → the record id its pending text names as awaiting verification."""
    out = {}
    for text in point.pending:
        if "verification" in text or "verified" in text:
            name = text.split(":", 1)[0]
            titled = [TITLES[t] for t in re.findall(r"\(([^)]+)\)", text) if t in TITLES]
            ids = titled or re.findall(r"\(([a-z0-9][a-z0-9.\-]+)\)", text) or re.findall(r"record ([a-z0-9][a-z0-9.\-]+)", text)
            out[name] = ids[0] if ids else NAMED.get(name, "?")
    return out


def main() -> int:
    from adroit.parameter_space import library, scan
    by_record: dict[str, list[str]] = defaultdict(list)
    lines = ["# R9: unverified records behind each portal's benchmark verdicts", "",
             "Generated by `docs/r9/portal_dependencies.py`. Each portal at its library benchmark point, with verified "
             "records only: the constraints left undecided because their record awaits verification, and the verdict "
             "they reach once it is verified (from the same point with unverified records allowed).", "",
             "| portal | constraint waiting | record | verdict once verified |", "|---|---|---|---|"]
    for e in library.ENTRIES:
        try:
            strict = scan.evaluate(e.model_class, e.point, False)
            loose = scan.evaluate(e.model_class, e.point, True)
        except Exception as error:  # noqa: BLE001 - reported per portal
            lines.append(f"| {e.id} | (not evaluated: {type(error).__name__}) | | |")
            continue
        waiting = blocked(strict)
        for name, record in sorted(waiting.items()):
            after = loose.excluded.get(name)
            lines.append(f"| {e.id} | {name} | `{record}` | {'excluded' if after else 'allowed' if after is False else 'undecided'} |")
            by_record[record].append(e.id)
        if not waiting:
            lines.append(f"| {e.id} | none | | |")
        print(e.id, len(waiting), flush=True)
    lines += ["", "## By record (verification order: the most portals first)", ""]
    lines += [f"- `{r}`: {len(p)} portal(s): {', '.join(p)}" for r, p in sorted(by_record.items(), key=lambda kv: -len(kv[1]))]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
