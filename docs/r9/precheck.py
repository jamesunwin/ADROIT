"""R9: a pre-check of every curated record against its source PDF, for the person who verifies them.

This is a reading aid, never a verification: a person still compares each record with its source and signs it
(`adroit records verify ID --by NAME --expected-hash HASH`). For each record the script reports:

- whether the source PDF is in the tools folder (`adroit records fetch-sources` fetches the rest);
- whether the figure or table label the record cites appears on the page it cites;
- whether each scalar number of the record's data (a limit, a central value, an uncertainty) appears on that page,
  as printed (to its stated digits); curves and tables in data files are not checked here;
- the record's current scientific hash, which the verify command pins.

Run from the repository root (no network, $0):

    uv run python docs/r9/precheck.py            # writes docs/r9/precheck.md
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
OUT = Path(__file__).with_name("precheck.md")

PRIORITY = ["planck-2018-omega"]          # every relic verdict depends on it (release plan, R9)


def page_text(pdf: Path, page: int) -> str:
    from pypdf import PdfReader
    reader = PdfReader(pdf)
    if not 1 <= page <= len(reader.pages):
        return ""
    return reader.pages[page - 1].extract_text() or ""


def label_found(label: str, text: str) -> bool | None:
    """Whether the cited label is on the page: its leading 'Fig. N', 'Table N' (Arabic or Roman, also 'Tables
    II–IV'), 'Eq. N', or 'abstract'; None for a label that names no such object ('main text')."""
    flat = re.sub(r"\s+", " ", text).lower()
    found = re.match(r"\s*(?:auxiliary\s+)?(fig(?:ure)?s?\.?|tables?|eq(?:uation)?s?\.?)\s*([0-9]+|[ivxl]+)\b", label, re.I)
    if found:
        kind, number = found.group(1).lower(), found.group(2).lower()
        words = ("fig", "figure") if kind.startswith("fig") else ("table",) if kind.startswith("tab") else ("eq", "equation")
        return any(re.search(rf"\b{w}s?\.?\s*{re.escape(number)}\b", flat) for w in words)
    if label.strip().lower().startswith("abstract"):
        return "abstract" in flat or None
    return None


def scalars(data, prefix: str = "") -> list[tuple[str, float]]:
    out = []
    if isinstance(data, dict):
        for k, v in data.items():
            out += scalars(v, f"{prefix}{k}.")
    elif isinstance(data, (int, float)) and not isinstance(data, bool):
        out.append((prefix.rstrip("."), float(data)))
    return out


def printed(value: float, text: str) -> bool:
    """Whether the number appears as printed: its decimal forms (0.107, .107, 10.7%) or a 10^n mantissa."""
    flat = text.replace("−", "-").replace(" ", "").replace(" ", "")
    forms = {f"{value:g}", f"{value:.4g}", f"{value:.3g}", f"{value:.2g}", f"{abs(value):g}"}
    forms |= {f.lstrip("0") for f in list(forms) if f.startswith("0.")}
    if 0 < abs(value) < 1:
        forms |= {f"{100 * value:g}%", f"{100 * value:.3g}%"}
    mantissa = f"{value:.3e}".split("e")[0].rstrip("0").rstrip(".")
    return any(f in flat for f in forms if f not in ("0", "1")) or (abs(value) > 1e3 or abs(value) < 1e-3) and mantissa in flat


def check(record) -> dict:
    from adroit.constraints import review
    from adroit.constraints.review_identity import fingerprint
    path = review.source_path(record)
    row = {"id": record.id, "verified": record.usable, "by": record.verified_by, "hash": fingerprint(record),
           "pdf": bool(path and path.exists()),
           "label": None, "numbers": [], "figure": record.figure}
    if record.figure is None or not row["pdf"]:
        return row
    text = page_text(path, record.figure.page)
    row["label"] = label_found(record.figure.label, text)
    row["numbers"] = [(name, value, printed(value, text)) for name, value in scalars(record.data)][:8]
    return row


def main() -> int:
    from adroit.constraints import database
    records = sorted(database.records(), key=lambda r: (r.id not in PRIORITY, r.usable, r.id))
    rows = [check(r) for r in records]
    lines = ["# R9 pre-check: each record against its source page (a reading aid, not a verification)", "",
             "Generated by `docs/r9/precheck.py` ($0, no network). A person verifies each record against its source "
             "and signs it with the command shown; the hash pins the scientific content that was reviewed.", "",
             "| record | state | source PDF | label on the cited page | scalar numbers on the page | scientific hash |",
             "|---|---|---|---|---|---|"]
    for row in rows:
        fig = row["figure"]
        where = f"arXiv:{fig.arxiv}, p. {fig.page}, {fig.label}" if fig else "no figure reference"
        label = {True: "yes", False: "**not found**", None: "not checked"}[row["label"]]
        numbers = ", ".join(f"{n} = {v:g}: {'yes' if ok else '**not found**'}" for n, v, ok in row["numbers"]) or "—"
        state = f"verified ({row['by']})" if row["verified"] else "awaits verification"
        lines.append(f"| `{row['id']}` | {state} | {'yes' if row['pdf'] else 'missing'}: {where} | {label} | {numbers} "
                     f"| `{row['hash']}` |")
    lines += ["", "To verify a record after reading it against its source:", "",
              "```", "uv run adroit records review ID      # shows the source, the data and the scientific hash",
              "uv run adroit records verify ID --by \"YOUR NAME\" --expected-hash HASH", "```"]
    OUT.write_text("\n".join(lines) + "\n")
    missing = [r["id"] for r in rows if not r["pdf"] and r["figure"] is not None]
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} records; {len(missing)} source PDFs missing")
    return 0


if __name__ == "__main__":
    sys.exit(main())
