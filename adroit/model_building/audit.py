"""The audit of a Lagrangian: is it valid, and what does it leave out? (DM12)

**Validity** (each problem an error; the model is valid if there is none):
- **statistics**: a term holds an even number of fermions;
- **Lorentz structure against the fields' spins**: each label needs its fields
  (a vector or axial coupling needs two fermions and a vector, or four
  fermions; a dipole, anapole or charge radius two fermions and a field
  strength; a scalar current two scalars and a vector; kinetic mixing two
  vectors; a scalar or pseudoscalar coupling no lone vector), and only spins 0,
  1/2 and 1 are understood;
- **mass dimension**: the operator's dimension (scalars and vectors 1,
  fermions 3/2, one more per derivative or field strength) and the coupling's
  must add to 4. A coupling of negative dimension marks an effective operator,
  whose validity is flagged (``eft.eft_flags``);
- **gauge invariance**: the U(1) charges add to zero and an SU(3) × SU(2)
  invariant exists (counted, ``groups.invariants``), on top of DM8's checks;
- **hermiticity** (DM8's check);
- **identities of self-conjugate fields**: a Majorana fermion's vector and
  tensor bilinears, and a real scalar's current, vanish.

**Flags** (reported, not errors): DM8's stability, perturbativity, anomaly,
contact-interaction and unitarity flags, and the EFT's validity.

**Missing terms**: for a model written above electroweak symmetry breaking,
the renormalizable operators its field content, charges and parity allow
(``lagrangian.general_lagrangian``) that none of its terms supplies. A term
that no stated symmetry forbids is generated by loops even if set to zero.
"""

from __future__ import annotations

from collections import Counter

import sympy
from pydantic import Field

from adroit.core.model_spec import FieldRole, ModelSpec, ModelTerm, Phase
from adroit.core.state import StrictModel
from adroit.library.interactions import model_checks
from adroit.model_building import eft
from adroit.model_building.content import content
from adroit.model_building.groups import Rep, invariants
from adroit.model_building.lagrangian import general_lagrangian

DIMENSION = {0.0: 1.0, 0.5: 1.5, 1.0: 1.0}
DERIVATIVES = {"scalar_current": 1, "dipole": 1, "tensor": 0, "anapole": 2, "charge_radius": 2,
               "kinetic_mixing": 2}
DIMENSIONFUL = {"v": 1, "m_h": 1, "m_W": 1, "m_Z": 1, "G_F": -2, "Lambda": 1}


class Problem(StrictModel):
    """One problem the audit found: the term, the check it failed, and why."""
    term: str
    check: str
    message: str


class AuditReport(StrictModel):
    """What the audit found."""

    model: str
    valid: bool
    problems: list[Problem] = Field(default_factory=list)
    flags: list[str] = Field(default_factory=list)
    missing: list[ModelTerm] = Field(default_factory=list)
    notes: list[str] = Field(default_factory=list)


def _label(term: ModelTerm) -> str:
    return term.text or f"{term.lorentz}: " + " ".join(("~" if o.conjugate else "") + o.field for o in term.fields)


def _kinds(spec: ModelSpec, term: ModelTerm) -> Counter:
    return Counter({0.0: "scalar", 0.5: "fermion", 1.0: "vector"}.get(spec.field(o.field).spin, "other")
                   for o in term.fields)


def lorentz_problems(spec: ModelSpec, term: ModelTerm) -> list[str]:
    """Statistics, and the Lorentz label against the spins of the term's fields."""
    k = _kinds(spec, term)
    if k["other"]:
        return ["a field of spin other than 0, 1/2 or 1: its Lorentz structure is not checked"]
    out = [] if k["fermion"] % 2 == 0 else [f"{k['fermion']} fermions: a Lorentz scalar needs an even number"]
    f, v, s, label = k["fermion"], k["vector"], k["scalar"], term.lorentz
    needs = {
        "vector": (f == 2 and v == 1) or (f == 4 and v == 0) or (s == 2 and v == 1 and f == 0),
        "axial": (f == 2 and v == 1) or (f == 4 and v == 0),
        "chiral": (f == 2 and v <= 1) or (f == 4 and v == 0),
        "dipole": f == 2 and v == 1, "anapole": f == 2 and v == 1, "charge_radius": f == 2 and v == 1,
        "tensor": (f == 2 and v == 1) or (f == 4 and v == 0),
        "scalar_current": s == 2 and v == 1 and f == 0,
        "kinetic_mixing": v == 2 and f == 0 and s == 0,
        "scalar": v % 2 == 0 and f in (0, 2, 4), "pseudoscalar": f in (2, 4) and v % 2 == 0,
    }
    if label in needs and not needs[label]:
        out.append(f"a {label} structure cannot be built from {f} fermion(s), {v} vector(s) and {s} scalar(s): "
                   "the Lorentz indices do not contract")
    return out


def operator_dimension(spec: ModelSpec, term: ModelTerm) -> float:
    """The mass dimension of a term's field content, with its derivatives.

    A scalar current (two scalars and a vector) carries one derivative whatever its label.
    """
    k = _kinds(spec, term)
    current = term.lorentz in ("vector", "axial", "chiral") and k["scalar"] == 2 and k["vector"] == 1 and not k["fermion"]
    return (sum(DIMENSION.get(spec.field(o.field).spin, 1.0) for o in term.fields)
            + DERIVATIVES.get(term.lorentz, 0) + (1 if current else 0))


def coupling_dimension(spec: ModelSpec, term: ModelTerm) -> float | None:
    """The mass dimension of a term's coupling expression, or None if it cannot be read."""
    declared = {c.name: c.mass_dimension for c in spec.couplings}
    from adroit.core.arithmetic import ArithmeticRefused, check_formula
    try:
        expr = sympy.sympify(check_formula(term.coupling))      # never text SymPy would run as Python
    except (sympy.SympifyError, TypeError, SyntaxError, ArithmeticRefused):
        return None
    t = sympy.Symbol("_t", positive=True)
    subs = {}
    for sym in expr.free_symbols:
        name = str(sym)
        dim = declared.get(name, DIMENSIONFUL.get(name, 1 if name.startswith("m_") else 0))
        subs[sym] = sym * t ** dim
    degrees = set()
    for part in sympy.Add.make_args(sympy.expand(expr)):
        scaled = sympy.powsimp(sympy.expand(part.subs(subs)))
        power = sympy.Poly(scaled, t).degree() if scaled.has(t) and scaled.is_polynomial(t) else None
        if power is None:
            lead = sympy.simplify(scaled.as_coeff_exponent(t)[1])
            power = float(lead)
        degrees.add(float(power))
    return degrees.pop() if len(degrees) == 1 else None


def dimension_problems(spec: ModelSpec, term: ModelTerm) -> tuple[list[str], list[str]]:
    """(problems, flags): the coupling's dimension against 4 − the operator's, and EFT validity."""
    if term.lorentz == "other":
        return [], [f"{_label(term)}: Lorentz structure 'other', so its derivatives and dimension are not checked"]
    d_op = operator_dimension(spec, term)
    d_c = coupling_dimension(spec, term)
    if d_c is None:
        return [], [f"{_label(term)}: the coupling's mass dimension could not be read"]
    if abs(d_op + d_c - 4) > 1e-9:
        return [f"the operator has dimension {d_op:g} and its coupling {d_c:g}; they must add to 4"], []
    if d_op > 4:
        dm = spec.dark_matter.mass_gev
        value = next((c.value for c in spec.couplings if c.name == term.coupling), None)
        cutoff = abs(value) ** (-1.0 / (d_op - 4)) if value else None
        return [], [f"{_label(term)}: dimension-{d_op:g} operator; " + "; ".join(eft.eft_flags(d_op, cutoff, dm) or
                                                                              ["EFT valid at the stated cutoff"])]
    return [], []


def gauge_invariant(spec: ModelSpec, term: ModelTerm) -> bool:
    """Whether the term's fields can form an SU(3) × SU(2) invariant (counted) with neutral U(1) charges.

    n copies of one spin-0 field of one generation, with the same conjugation, commute, so they enter as the
    symmetric n-th power of its representation: ε_ij D^i D^j and ε_abc T^a T^b T^c vanish (release audit minor).
    Fermions, whose symmetry depends on the Lorentz contraction, and fields with generations stay distinct.
    """
    copies = Counter((o.field, o.conjugate) for o in term.fields)
    reps = []
    for (name, conjugate), n in copies.items():
        f = spec.field(name)
        rep = Rep(f.charges.su3, f.charges.su2, 1, conjugate=conjugate)
        if f.spin == 0 and f.generations == 1:
            reps.append((rep, n, True))
        else:
            reps += [(rep, 1, True)] * n
    return invariants(reps) > 0


def _identity_problems(spec: ModelSpec, term: ModelTerm) -> list[str]:
    names = Counter(o.field for o in term.fields)
    out = []
    for name, n in names.items():
        f = spec.field(name)
        if f.self_conjugate and f.spin == 0.5 and n == 2 and term.lorentz in ("vector", "tensor", "dipole", "charge_radius"):
            out.append(f"the {term.lorentz} bilinear of the Majorana fermion {name} vanishes identically")
        if f.self_conjugate and f.spin == 0.5 and n == 2 and term.lorentz in ("VV", "VA", "TT"):     # a contact's dark
            out.append(f"the {term.lorentz} contact's {'vector' if term.lorentz[0] == 'V' else 'tensor'} bilinear of "  # bilinear
                       f"the Majorana fermion {name} vanishes identically")          # first (the audit loop's AL4-08)
        if f.self_conjugate and f.spin == 0 and n == 2 and term.lorentz == "scalar_current":
            out.append(f"the current of the real scalar {name} vanishes identically")
    return out


def validity(spec: ModelSpec) -> tuple[list[Problem], list[str]]:
    """Every validity problem, and the dimension flags."""
    problems, flags = [], []
    gauge = set(model_checks.gauge_problems(spec))
    for term in spec.terms:
        label = _label(term)
        for message in lorentz_problems(spec, term):
            problems.append(Problem(term=label, check="Lorentz", message=message))
        dim_problems, dim_flags = dimension_problems(spec, term)
        problems += [Problem(term=label, check="dimension", message=m) for m in dim_problems]
        flags += dim_flags
        problems += [Problem(term=label, check="identity", message=m) for m in _identity_problems(spec, term)]
        if spec.phase is Phase.unbroken and not gauge_invariant(spec, term):
            problems.append(Problem(term=label, check="gauge", message="no SU(3) × SU(2) invariant can be formed"))
    problems += [Problem(term="", check="gauge", message=m) for m in gauge]
    herm, _notes = model_checks.hermiticity_problems(spec)
    problems += [Problem(term="", check="hermiticity", message=m) for m in herm]
    return problems, flags


def _key(spec: ModelSpec, term: ModelTerm) -> tuple:
    """A term's identity for comparison: fields with conjugation (up to overall conjugation) and its class."""
    def occ(flip: bool) -> tuple:
        out = []
        for o in term.fields:
            real = spec.field(o.field).self_conjugate
            out.append((o.field, False if real else o.conjugate != flip))
        return tuple(sorted(out))
    fermions = [o.field for o in term.fields if spec.field(o.field).spin == 0.5]
    vectors = [o.field for o in term.fields if spec.field(o.field).spin == 1]
    if not fermions:
        kind = {"kinetic_mixing": "kinetic_mixing", "scalar_current": "current"}.get(term.lorentz, "potential")
        if term.lorentz in ("vector", "axial", "chiral") and vectors:
            kind = "current"
    else:
        dark_dirac = (len(set(fermions)) == 1 and not spec.field(fermions[0]).self_conjugate
                      and spec.field(fermions[0]).role is not FieldRole.standard_model)
        if dark_dirac:
            kind = term.lorentz
        else:
            kind = "fermion_current" if vectors and term.lorentz in ("vector", "axial", "chiral") else "fermion_yukawa"
    return (min(occ(False), occ(True)), kind)


def _renamed(term: ModelTerm, mapping: dict[str, str]) -> ModelTerm:
    if not any(o.field in mapping for o in term.fields):
        return term
    return term.model_copy(update={"fields": [o.model_copy(update={"field": mapping.get(o.field, o.field)})
                                              for o in term.fields]})


def missing_terms(spec: ModelSpec) -> tuple[list[ModelTerm], list[str]]:
    """(terms allowed but absent, notes); only for a model written above electroweak symmetry breaking."""
    from adroit.model_building.spec import general_spec, sm_identity
    if spec.phase is not Phase.unbroken:
        return [], ["missing terms are found for a model written above electroweak symmetry breaking (phase "
                    "'unbroken', charges with hypercharge); this one is written below it"]
    try:
        ops = general_lagrangian(content(spec))
    except ValueError as error:
        return [], [f"the generator cannot hold this field content: {error}"]
    general = general_spec(spec.model_copy(update={"terms": [], "couplings": []}), ops)
    identity = sm_identity(spec)
    mapping = identity.shared                            # shared fields keep the generator's name in `general`
    names = {f.name for f in general.fields}
    present = {_key(general, t) for t in (_renamed(t, mapping) for t in spec.terms)
               if all(o.field in names for o in t.fields)}
    missing = [t for t in general.terms if _key(general, t) not in present]
    notes = identity.notes + list(dict.fromkeys(n for n in general.assumptions if "tadpole" in n))
    for f in spec.fields:
        if f.spin == 0.5 and not f.self_conjugate and not f.chirality and f.role is not FieldRole.standard_model:
            majorana = [op for op in ops if op.structure == "mass" and op.fields == [f.name, f.name]
                        and len(set(op.blocks)) == 1]
            if majorana:
                notes.append(f"{f.name} is written as a Dirac fermion, but no conserved charge forbids its Majorana "
                             f"masses ({', '.join(op.text for op in majorana)}): without one it is a pseudo-Dirac pair")
    return missing, notes


NATURAL_ZERO = ("technically natural only if a symmetry protects this zero; otherwise loops regenerate the term, "
                "and the zero is a benchmark choice")


def zero_couplings(spec: ModelSpec) -> list[str]:
    """A flag for each coupling set to exactly zero: such a zero is stable under radiative corrections only if a
    symmetry forbids the term ('t Hooft's technical naturalness)."""
    out = []
    for c in spec.couplings:
        if c.value == 0:
            terms = [t.text or t.lorentz for t in spec.terms if t.coupling == c.name]
            out.append(f"{c.name} = 0" + (f" ({', '.join(terms)})" if terms else "") + f": {NATURAL_ZERO}")
    return out


def audit(spec: ModelSpec) -> AuditReport:
    """Validity, flags (among them the naturalness of any coupling set to zero) and missing terms of a model."""
    if spec.scalar_potential is not None:
        from adroit.model_building.scalar_contract import resolved_spec
        try:
            spec=resolved_spec(spec)
        except ValueError as error:
            return AuditReport(model=spec.name,valid=False,problems=[Problem(term="declared scalar potential",
                check="explicit model contract",message=str(error))])
    problems, flags = validity(spec)
    checks = model_checks.check(spec)
    symbolic = {c.name for c in spec.couplings if c.value is None}
    flags += [f for f in checks.flags
              if not (f in checks.coefficients and any(f"'{name}'" in f for name in symbolic))]
    flags += zero_couplings(spec)
    missing, notes = missing_terms(spec)
    return AuditReport(model=spec.name, valid=not problems, problems=problems, flags=flags, missing=missing,
                       notes=notes)
